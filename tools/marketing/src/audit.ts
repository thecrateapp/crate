export interface MediaFinding {
  path: string;
  durationSeconds: number;
  hasAudio: boolean;
  sheet: string;
}

export interface Soundtrack {
  film: string;
  track: string;
}

const SHEET_COLUMNS = 6;

export function contactSheetArgs(
  input: string,
  output: string,
  durationSeconds: number,
): string[] {
  const rows = Math.max(
    1,
    Math.ceil(Math.ceil(durationSeconds) / SHEET_COLUMNS),
  );
  return [
    "-hide_banner",
    "-loglevel",
    "error",
    "-y",
    "-i",
    input,
    "-vf",
    `fps=1,scale=320:-2,tile=${SHEET_COLUMNS}x${rows}`,
    "-frames:v",
    "1",
    output,
  ];
}

export function declaredSoundtracks(filmsSource: string): Soundtrack[] {
  const tracks: Soundtrack[] = [];
  const start = filmsSource.search(/export const films\b/);
  const body = start === -1 ? filmsSource : filmsSource.slice(start);
  const pattern = /^ {2}(\w+):\s*\{\s*$[\s\S]*?^ {4}track:\s*"([^"]+)"/gm;
  for (const match of body.matchAll(pattern)) {
    tracks.push({ film: match[1], track: match[2] });
  }
  return tracks;
}

export function renderAuditReport(
  findings: MediaFinding[],
  soundtracks: Soundtrack[],
  date: string,
): string {
  const media = [...findings]
    .sort((a, b) => a.path.localeCompare(b.path))
    .map(
      (finding) =>
        `| \`${finding.path}\` | ${finding.durationSeconds.toFixed(1)} s | ${
          finding.hasAudio ? "yes" : "no"
        } | \`${finding.sheet}\` | ${
          finding.hasAudio ? "review" : "check visuals"
        } |`,
    );
  const tracks = soundtracks.map(
    (soundtrack) =>
      `| ${soundtrack.film} | ${soundtrack.track} | needs a licence or replacement |`,
  );
  return [
    `# Rights audit of website media (${date})`,
    "",
    "Generated by `tools/marketing/audit-screencasts.ts`. Every file with audio and every declared soundtrack needs",
    "a licence before it can appear in a public post or reel. Visuals need a manual check for album covers,",
    "artist names and artwork from a library we don't have rights to show.",
    "",
    "## Media",
    "",
    "| File | Duration | Audio | Contact sheet | Action |",
    "|---|---|---|---|---|",
    ...media,
    "",
    "## Declared soundtracks",
    "",
    "| Film | Track | Action |",
    "|---|---|---|",
    ...(tracks.length > 0 ? tracks : ["| none | | |"]),
    "",
  ].join("\n");
}
