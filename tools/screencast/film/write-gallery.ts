import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { GALLERY } from "./gallery";

const WEB = "../../app/web";
const SIZES = { large: 2560, small: 1280 };
const PORTRAIT_SIZES = { large: 1620, small: 1080 };
const HEIGHT_RATIO = 1080 / 1920;
const PORTRAIT_RATIO = 1350 / 1080;

const [framesDir, portraitDir] = process.argv.slice(2);
if (!framesDir || !portraitDir) {
  console.error(
    "Usage: tsx film/write-gallery.ts <16:9 frames dir> <4:5 frames dir>",
  );
  process.exit(1);
}

function rendered(dir: string): string[] {
  const files = readdirSync(dir)
    .filter((file) => file.endsWith(".png"))
    .sort(
      (a, b) =>
        Number(a.match(/(\d+)\.png$/)?.[1]) -
        Number(b.match(/(\d+)\.png$/)?.[1]),
    );
  if (files.length !== GALLERY.length) {
    console.error(
      `Rendered ${files.length} frames in ${dir} for ${GALLERY.length} gallery entries.`,
    );
    process.exit(1);
  }
  return files.map((file) => join(dir, file));
}

const frames = rendered(framesDir);
const portraits = rendered(portraitDir);

function encode(
  source: string,
  dir: string,
  sizes: Record<"large" | "small", number>,
  name: (size: "large" | "small", width: number) => string,
) {
  return Object.fromEntries(
    (Object.entries(sizes) as ["large" | "small", number][]).map(
      ([size, width]) => {
        const file = name(size, width);
        execFileSync("cwebp", [
          "-quiet",
          "-q",
          "80",
          "-m",
          "6",
          "-resize",
          String(width),
          "0",
          source,
          "-o",
          join(dir, file),
        ]);
        return [size, { file, bytes: statSync(join(dir, file)).size }];
      },
    ),
  ) as Record<"large" | "small", { file: string; bytes: number }>;
}

const entries = GALLERY.map((entry, index) => {
  const dir = join(WEB, "public/gallery", entry.app);
  mkdirSync(dir, { recursive: true });
  const wide = encode(frames[index], dir, SIZES, (size, width) =>
    size === "large" ? `${entry.id}.webp` : `${entry.id}-${width}.webp`,
  );
  const tall = encode(portraits[index], dir, PORTRAIT_SIZES, (size, width) =>
    size === "large"
      ? `${entry.id}-portrait.webp`
      : `${entry.id}-portrait-${width}.webp`,
  );
  const url = (file: string) => `/gallery/${entry.app}/${file}`;
  console.log(
    `${entry.app}/${entry.id}: ${Math.round(
      wide.small.bytes / 1024,
    )} KB wide, ${Math.round(tall.small.bytes / 1024)} KB portrait`,
  );
  return {
    id: entry.id,
    app: entry.app,
    title: entry.title,
    caption: entry.caption,
    alt: entry.alt,
    src: url(wide.large.file),
    srcSmall: url(wide.small.file),
    width: SIZES.large,
    height: Math.round(SIZES.large * HEIGHT_RATIO),
    portrait: url(tall.large.file),
    portraitSmall: url(tall.small.file),
    portraitWidth: PORTRAIT_SIZES.large,
    portraitHeight: Math.round(PORTRAIT_SIZES.large * PORTRAIT_RATIO),
  };
});

const body = `// Generated by tools/screencast/film/write-gallery.ts from film/gallery.ts. Do not edit by hand.
export interface GalleryShot {
  id: string;
  app: "listen" | "admin";
  title: string;
  caption: string;
  alt: string;
  src: string;
  srcSmall: string;
  width: number;
  height: number;
  portrait: string;
  portraitSmall: string;
  portraitWidth: number;
  portraitHeight: number;
}

export const gallery: GalleryShot[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(WEB, "src/content/gallery.ts"), body);
console.log(`Wrote ${entries.length} shots to ${WEB}/src/content/gallery.ts`);
