import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import admin from "./data/admin.beats.json";
import listen from "./data/listen.beats.json";
import { barTime, type BeatGrid } from "./grid";
import type { FilmId } from "./storyboard";

// Encodes the rendered masters for the web and writes app/web/src/content/films.ts.
const WEB = "../../app/web";
const MASTERS = "out/film";
const FORMATS = ["16x9", "4x5"] as const;

const FILMS: Record<
  FilmId,
  { grid: BeatGrid; poster: number; chapters: [string, number][] }
> = {
  listen: {
    grid: listen as BeatGrid,
    poster: 13,
    chapters: [
      ["Library", 165],
      ["Player", 171],
      ["Playlists", 179],
      ["Crates", 183],
      ["And more", 189],
    ],
  },
  admin: {
    grid: admin as BeatGrid,
    poster: 5,
    chapters: [
      ["Health", 53],
      ["Imports", 57],
      ["Enrichment", 61],
      ["Analysis", 65],
      ["Acquisition", 73],
      ["Agents", 76],
    ],
  },
};

const ffmpeg = (args: string[]) =>
  execFileSync(
    "ffmpeg",
    ["-hide_banner", "-loglevel", "error", "-y", ...args],
    { stdio: "inherit" },
  );
const kb = (file: string) => Math.round(statSync(file).size / 1024);

const out = join(WEB, "public/film");
mkdirSync(out, { recursive: true });
const manifest: Record<string, unknown> = {};

for (const [id, film] of Object.entries(FILMS) as [
  FilmId,
  (typeof FILMS)[FilmId],
][]) {
  const sources: Record<string, unknown> = {};
  for (const format of FORMATS) {
    const master = join(MASTERS, `${id}-film-${format}.mp4`);
    const base = `${id}-${format}`;
    const webm = join(out, `${base}.webm`);
    const mp4 = join(out, `${base}.mp4`);
    const poster = join(out, `${base}-poster.webp`);
    const still = join(out, `${base}-poster.png`);
    ffmpeg([
      "-i",
      master,
      "-c:v",
      "libvpx-vp9",
      "-crf",
      "44",
      "-b:v",
      "0",
      "-row-mt",
      "1",
      "-deadline",
      "good",
      "-cpu-used",
      "2",
      "-pix_fmt",
      "yuv420p",
      "-c:a",
      "libopus",
      "-b:a",
      "96k",
      webm,
    ]);
    ffmpeg([
      "-i",
      master,
      "-c:v",
      "libx264",
      "-preset",
      "slow",
      "-crf",
      "30",
      "-tune",
      "animation",
      "-profile:v",
      "high",
      "-pix_fmt",
      "yuv420p",
      "-c:a",
      "aac",
      "-b:a",
      "128k",
      "-movflags",
      "+faststart",
      mp4,
    ]);
    ffmpeg(["-ss", String(film.poster), "-i", master, "-frames:v", "1", still]);
    execFileSync("cwebp", ["-quiet", "-q", "78", still, "-o", poster]);
    rmSync(still);
    console.log(
      `${base}: webm ${kb(webm)} KB, mp4 ${kb(mp4)} KB, poster ${kb(
        poster,
      )} KB`,
    );
    sources[format] = {
      webm: `/film/${base}.webm`,
      mp4: `/film/${base}.mp4`,
      poster: `/film/${base}-poster.webp`,
    };
  }
  manifest[id] = {
    duration: Math.round(film.grid.duration * 100) / 100,
    track: `${film.grid.artist} — ${film.grid.title}`,
    sources,
    chapters: film.chapters.map(([label, bar]) => ({
      label,
      time: Math.round(barTime(film.grid, bar) * 100) / 100,
    })),
  };
}

const body = `// Generated by tools/screencast/film/write-films.ts. Do not edit by hand.
export interface FilmSources {
  webm: string;
  mp4: string;
  poster: string;
}

export interface FilmChapter {
  label: string;
  time: number;
}

export interface Film {
  duration: number;
  track: string;
  sources: { "16x9": FilmSources; "4x5": FilmSources };
  chapters: FilmChapter[];
}

export const films: Record<"listen" | "admin", Film> = ${JSON.stringify(
  manifest,
  null,
  2,
)};
`;
writeFileSync(join(WEB, "src/content/films.ts"), body);
console.log("Wrote app/web/src/content/films.ts");
