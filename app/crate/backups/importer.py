# Kinds whose credentials an operator holds. SFTP keys are generated by Crate.
IMPORTABLE_KINDS = ("s3", "b2", "gdrive", "dropbox", "local")
SIDECAR_SNAPSHOT_PATH = "/crate.sql.gz"
SIDECAR_HOST = "crate"
OPEN_TIMEOUT_SECONDS = 300

# Where each secret may come from, after its own name and CRATE_IMPORT_<NAME>.
SECRET_ALIASES: dict[str, tuple[str, ...]] = {
    "repository_password": ("RESTIC_PASSWORD",),
    "access_key_id": ("CRATE_OFFSITE_R2_ACCESS_KEY_ID", "AWS_ACCESS_KEY_ID"),
    "secret_access_key": (
        "CRATE_OFFSITE_R2_SECRET_ACCESS_KEY",
        "AWS_SECRET_ACCESS_KEY",
    ),
    "key_id": ("B2_ACCOUNT_ID",),
    "application_key": ("B2_ACCOUNT_KEY",),
    "client_secret": ("RCLONE_CONFIG_GDRIVE_CLIENT_SECRET",),
    "token": ("RCLONE_CONFIG_GDRIVE_TOKEN",),
}


class ImportConflict(RuntimeError):
    """A destination already holds this name or repository; the message says which."""


@dataclass(slots=True)
class OpenedRepository:
    """What opening the repository showed, before anything is stored."""

    snapshots: list[dict[str, Any]]
    repository_bytes: int | None

    @property
    def sidecar_snapshots(self) -> int:
        return sum(
            1
            for s in self.snapshots
            if s.get("host") == SIDECAR_HOST
            and SIDECAR_SNAPSHOT_PATH in (s.get("paths") or [])
        )


@dataclass(slots=True)
class ImportResult:
    action: str  # created, replaced or unchanged
    destination: dict[str, Any]
    opened: OpenedRepository | None = None
    test_task_id: str | None = None
    notes: list[str] = field(default_factory=list)


# ── reading secrets and settings ──────────────────────────────────


def parse_secret_stream(raw: str) -> dict[str, str]:
    """A JSON object, or ``KEY=VALUE`` lines (``env`` output, a dotenv file)."""
    text = raw.strip()
    if not text:
        return {}
    if text.startswith("{"):
        try:
            payload = json.loads(text)
        except json.JSONDecodeError as exc:
            raise DestinationError("stdin is not a valid JSON object") from exc
        if not isinstance(payload, dict):
            raise DestinationError("stdin must hold one JSON object")
        return {
            str(k): v if isinstance(v, str) else json.dumps(v)
            for k, v in payload.items()
            if v is not None
        }
    values: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip().removeprefix("export ").strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]
        values[key] = value
    return values


def _lookup(source: Mapping[str, str], name: str) -> str | None:
    for key in (name, f"CRATE_IMPORT_{name.upper()}", *SECRET_ALIASES.get(name, ())):
        value = source.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return None


def read_secrets(kind: str, source: Mapping[str, str]) -> tuple[dict[str, str], str]:
    """The provider secrets and the repository password found in ``source``."""
    spec = providers.provider(kind)
    found = {
        f.name: value
        for f in spec.secret_fields
        if not f.system and (value := _lookup(source, f.name)) is not None
    }
    password = _lookup(source, "repository_password")
    if password is None:
        raise DestinationError(
            "The repository password is missing: set RESTIC_PASSWORD or "
            "CRATE_IMPORT_REPOSITORY_PASSWORD, or send repository_password on stdin"
        )
    if len(password) < MIN_REPOSITORY_PASSWORD:
        raise DestinationError(
            "An imported repository password has at least "
            f"{MIN_REPOSITORY_PASSWORD} characters"
        )
    return found, password


def sidecar_config(kind: str, source: Mapping[str, str]) -> dict[str, Any]:
    """The repository location as ``crate-backup-offsite`` configures it."""
    if kind == "s3":
        endpoint = source.get("CRATE_OFFSITE_R2_ENDPOINT", "").strip()
        account = source.get("CRATE_OFFSITE_R2_ACCOUNT_ID", "").strip()
        if not endpoint and account:
            endpoint = f"https://{account}.r2.cloudflarestorage.com"
        config: dict[str, Any] = {"region": "auto"}
        if endpoint:
            config["endpoint"] = endpoint
        if source.get("CRATE_OFFSITE_R2_BUCKET", "").strip():
            config["bucket"] = source["CRATE_OFFSITE_R2_BUCKET"].strip()
        if source.get("CRATE_OFFSITE_R2_PATH", "").strip():
            config["prefix"] = source["CRATE_OFFSITE_R2_PATH"].strip()
        return config
    if kind == "gdrive":
        config = {
            "path": source.get("CRATE_OFFSITE_GDRIVE_PATH", "").strip()
            or "crate-backups"
        }
        if source.get("RCLONE_CONFIG_GDRIVE_ROOT_FOLDER_ID", "").strip():
            config["root_folder_id"] = source[
                "RCLONE_CONFIG_GDRIVE_ROOT_FOLDER_ID"
            ].strip()
        if source.get("RCLONE_CONFIG_GDRIVE_CLIENT_ID", "").strip():
            config["client_id"] = source["RCLONE_CONFIG_GDRIVE_CLIENT_ID"].strip()
        return config
    raise DestinationError(
        "--from-sidecar reads the crate-backup-offsite settings of s3 (R2) or gdrive"
    )


# ── opening the repository ────────────────────────────────────────


def open_existing_repository(
    kind: str,
    config: Mapping[str, Any],
    credentials: Mapping[str, str],
    password: str,
    *,
    should_cancel: Callable[[], bool] | None = None,
) -> OpenedRepository:
    """Open the repository with its password and list it; never initialise it."""
    missing = tools_available()
    if missing:
        raise BackupError(
            f"This container has no {' or '.join(missing)}; run the import in "
            "crate-maintenance-worker"
        )
    secret_values = [password, *credentials.values()]
    with tempfile.TemporaryDirectory(prefix="crate-import-") as raw_dir:
        work_dir = Path(raw_dir)
        try:
            target = providers.restic_target(
                kind,
                config,
                credentials,
                backup_dir=backup_dir(),
                work_dir=work_dir,
            )
            runner = Runner(target, password, work_dir, should_cancel=should_cancel)
            try:
                runner.run("cat", "config", timeout_seconds=OPEN_TIMEOUT_SECONDS)
            except ResticError as exc:
                raise ResticError(
                    "Cannot open the repository with this password (a wrong "
                    f"password, location or credential, or no repository): {exc}"
                ) from None
            snapshots = compact_snapshots(list_snapshots(runner))
            size = repository_size(runner)
        except (ResticError, OSError) as exc:
            raise BackupError(scrub(str(exc), secret_values)) from None
    return OpenedRepository(snapshots=snapshots, repository_bytes=size)


# ── matching existing destinations ────────────────────────────────


def _same_name(a: str, b: str) -> bool:
    return " ".join(a.split()).casefold() == " ".join(b.split()).casefold()


def find_matches(
    kind: str, name: str, config: Mapping[str, Any]
) -> list[dict[str, Any]]:
    """Destinations with the same name, or the same kind and repository location."""
    location = providers.location_summary(kind, config)
    return [
        row
        for row in list_backup_destinations()
        if _same_name(str(row["name"]), name)
        or (
            row["kind"] == kind
            and providers.location_summary(kind, row["config"] or {}) == location
        )
    ]


def _user_config(kind: str, config: Mapping[str, Any]) -> dict[str, Any]:
    spec = providers.provider(kind)
    return {
        k: v
        for k, v in config.items()
        if (field_spec := spec.config_field(k)) is not None and not field_spec.system
    }


def _is_identical(
    row: Mapping[str, Any],
    kind: str,
    config: Mapping[str, Any],
    credentials: Mapping[str, str],
    password: str,
) -> bool:
    if row["kind"] != kind:
        return False
    if _user_config(kind, row["config"] or {}) != _user_config(kind, config):
        return False
    try:
        stored = load_destination_secrets(row)
    except Exception:
        return False
    return stored.repository_password == password and stored.credentials == dict(
        credentials
    )


# ── the import ────────────────────────────────────────────────────


def _queue_test(destination_id: str) -> str | None:
    from crate.db.repositories.tasks import create_task_dedup

    task_id = create_task_dedup(
        "backup_test_destination",
        {"destination_id": destination_id},
        dedup_key=f"backup_test_destination:{destination_id}",
    )
    return str(task_id) if task_id else None


def _notes(opened: OpenedRepository) -> list[str]:
    notes = []
    if opened.sidecar_snapshots:
        notes.append(
            f"{opened.sidecar_snapshots} snapshots of {SIDECAR_SNAPSHOT_PATH} from "
            f"host {SIDECAR_HOST} (the crate-backup-offsite sidecar). The engine's "
            "retention (restic forget --group-by host) prunes them together with "
            "its own copies, so they thin out to the policy's counts (D6)."
        )
    notes.append(
        "Download a new recovery kit from Admin (Backups) and confirm it: the "
        "last kit does not cover this destination."
    )
    return notes


def import_destination(
    *,
    kind: str,
    name: str,
    config: Mapping[str, Any],
    credentials: Mapping[str, str],
    repository_password: str,
    replace: bool = False,
    queue_test: bool = True,
    opener: Callable[..., OpenedRepository] | None = None,
) -> ImportResult:
    """Register an existing repository; see the module docstring."""
    if kind not in IMPORTABLE_KINDS:
        raise DestinationError(
            f"{kind} cannot be imported; importable kinds: {', '.join(IMPORTABLE_KINDS)}"
        )
    clean_config, clean_credentials = providers.validate(kind, config, credentials)
    missing = providers.provider(kind).missing_secrets(clean_credentials)
    if missing:
        raise DestinationError(f"Missing: {', '.join(missing)}")
    if kind in ("gdrive", "dropbox"):
        # Same check the engine makes before every run (D4): the install's client.
        providers.install_oauth_client(kind, clean_config, clean_credentials)

    matches = find_matches(kind, name, clean_config)
    if len(matches) > 1:
        raise ImportConflict(
            "More than one destination already has this name or repository: "
            + ", ".join(f"{m['name']} ({m['id']})" for m in matches)
        )
    existing = matches[0] if matches else None
    if existing is not None and _is_identical(
        existing, kind, clean_config, clean_credentials, repository_password
    ):
        row = get_backup_destination(existing["id"]) or existing
        return ImportResult("unchanged", public_destination(row))
    if existing is not None and not replace:
        raise ImportConflict(
            f"The destination {existing['name']} ({existing['id']}) already has this "
            "name or repository with other settings; pass --replace to overwrite it"
        )

    opened = (opener or open_existing_repository)(
        kind, clean_config, clean_credentials, repository_password
    )
    if existing is None:
        destination = create_destination(
            kind=kind,
            name=name,
            config=clean_config,
            secrets=clean_credentials,
            repository_password=repository_password,
        )
        action = "created"
    else:
        destination = _replace(
            existing, name, clean_config, clean_credentials, repository_password
        )
        action = "replaced"
    # The listing the Admin snapshots tab reads, the sidecar's snapshots included.
    record_destination_check(
        destination["id"],
        status="ok",
        snapshot_count=len(opened.snapshots),
        repository_bytes=opened.repository_bytes,
        initialized=True,
        snapshots=opened.snapshots,
    )
    row = get_backup_destination(destination["id"])
    result = ImportResult(
        action, public_destination(row or destination), opened, notes=_notes(opened)
    )
    if queue_test:
        # The full test also writes, reads and deletes a probe file: pruning
        # needs delete rights, which opening the repository does not prove.
        result.test_task_id = _queue_test(destination["id"])
    return result


def _replace(
    existing: Mapping[str, Any],
    name: str,
    config: Mapping[str, Any],
    credentials: Mapping[str, str],
    password: str,
) -> dict[str, Any]:
    stored = load_destination_secrets(existing)
    removed = {key: None for key in stored.credentials if key not in credentials}
    updated = update_destination(
        str(existing["id"]),
        name=name,
        config=dict(config),
        secrets={**removed, **credentials},
    )
    if stored.repository_password != password:
        new_ref = store_secret(PASSWORD_SCOPE, {"password": password})
        old_ref = replace_repository_password(str(existing["id"]), new_ref)
        if old_ref is None:
            revoke_secret(new_ref)
            raise ImportConflict("The destination disappeared during the import")
        try:
            revoke_secret(old_ref)
        except Exception:  # pragma: no cover - a stale ref must not fail the import
            pass
    return updated


def environment_source() -> dict[str, str]:
    return dict(os.environ)


