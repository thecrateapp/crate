"""Import an existing restic repository as a backup destination (admin backups, BK6).

BK6 moves production's off-site copies from the ``crate-backup-offsite`` sidecar to
the engine: the same repositories, opened with the same restic password. Admin
never accepts a repository password (the engine generates one per destination),
so the import is a command run inside the maintenance worker:

    python -m crate.backups.cli import-destination --kind s3 --name "Cloudflare R2" ...

Secrets never come from the command line. They are read from the environment or
from stdin (a JSON object, or ``KEY=VALUE`` lines such as ``env`` prints), under
their own names (``repository_password``, ``access_key_id``...), as
``CRATE_IMPORT_<NAME>``, or under the sidecar's names (``RESTIC_PASSWORD``,
``CRATE_OFFSITE_R2_*``, ``RCLONE_CONFIG_GDRIVE_*``). ``--from-sidecar`` also takes
the repository's location from the sidecar's variables.

The import opens the repository before it stores anything (``restic cat config``,
then its snapshots and size) and never initialises one: a wrong password, a wrong
bucket or a missing repository stops it. Secrets go through
``crate.backups.destinations`` and ``crate.credentials`` like any other
destination's. A destination with the same name or the same repository is not
overwritten unless ``replace`` is set; importing the same settings twice changes
nothing.

Retention (decision D6): the sidecar's snapshots (host ``crate``, path
``/crate.sql.gz``) and the engine's (host ``crate``, path ``/crate.dump``) share a
``restic forget --group-by host`` group, so the engine's retention prunes both
together and the sidecar's history thins out to the policy's counts. The sidecar's
own ``--group-by host,paths`` never prunes the engine's snapshots.
"""

