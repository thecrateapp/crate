"""The Python images and CI install only from the hashed locks (make python-lock)."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

APP_ROOT = Path(__file__).resolve().parents[1]
ROOT = APP_ROOT.parent
LOCKS = (
    "requirements-test.txt",
    "requirements.txt",
    "requirements-worker.txt",
    "requirements-worker-core.txt",
    "requirements-api.txt",
    "requirements-beat-this.txt",
)
WORKFLOWS = ROOT / ".github/workflows"


def _pins(lock: str) -> dict[tuple[str, str], str]:
    pins = {}
    for line in (APP_ROOT / lock).read_text().splitlines():
        match = re.match(r"^([A-Za-z0-9_.-]+)==(\S+)(?: ; (.+?))? \\$", line)
        if match:
            name, version, marker = match.groups()
            pins[(name.lower(), marker or "")] = version
    return pins


@pytest.mark.parametrize("lock", LOCKS)
def test_every_locked_requirement_carries_hashes(lock: str) -> None:
    text = (APP_ROOT / lock).read_text()
    requirements = re.findall(r"^[A-Za-z0-9_.-]+(?:==| @ )", text, re.M)

    assert requirements
    assert text.startswith("# This file was autogenerated by uv")
    assert "#    make python-lock\n" in text
    assert len(re.findall(r"^\S.* \\\n    --hash=sha256:", text, re.M)) == len(
        requirements
    )
    assert (APP_ROOT / lock.replace(".txt", ".in")).exists()


def test_the_locks_agree_on_every_shared_version() -> None:
    seen: dict[tuple[str, str], tuple[str, str]] = {}
    for lock in LOCKS:
        for key, version in _pins(lock).items():
            first = seen.setdefault(key, (version, lock))
            assert first[0] == version, (key, first, (version, lock))


def test_the_images_install_only_from_hashed_locks() -> None:
    dockerfile = (APP_ROOT / "Dockerfile").read_text()
    installs = re.findall(r"pip install [^\n]*-r (\S+)", dockerfile)

    assert set(installs) == {
        "requirements-api.txt",
        "requirements-worker-core.txt",
        "requirements-worker.txt",
        "requirements-beat-this.txt",
    }
    for line in re.findall(r"pip install [^\n]*-r \S+", dockerfile):
        assert "--require-hashes" in line, line
    assert "--index-url" not in dockerfile


def test_ci_installs_the_backend_from_hashed_locks() -> None:
    installs = [
        line.strip()
        for workflow in WORKFLOWS.glob("*.yml")
        for line in workflow.read_text().splitlines()
        if re.search(r"pip install .*-r requirements", line)
    ]

    assert installs
    for line in installs:
        assert "--require-hashes" in line, line
        assert re.search(r"-r requirements[a-z-]*\.txt$", line), line


def test_ci_checks_the_locks_and_audits_them() -> None:
    workflow = (WORKFLOWS / "test-backend.yml").read_text()

    assert "make python-lock" in workflow
    assert "git diff --exit-code -- 'app/requirements*.txt'" in workflow
    assert "make python-audit" in workflow
    assert '- "app/pip-audit-ignore.txt"' in workflow


def test_accepted_advisories_are_ids_with_a_justification() -> None:
    for line in (APP_ROOT / "pip-audit-ignore.txt").read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            assert re.match(r"^(PYSEC|GHSA|CVE)-[\w-]+\s+#\s*\S", line), line
