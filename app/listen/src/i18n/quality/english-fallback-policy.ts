export function buildEnglishFallbackAllowlist(
  sourceKeys: Iterable<string>,
): Set<string> {
  const allowlist = new Set(COMPLETED_ENGLISH_FALLBACK_ALLOWLIST);
  for (const key of sourceKeys) {
    if (
      !COMPLETED_LOCALIZATION_PREFIXES.some((prefix) => key.startsWith(prefix))
    ) {
      allowlist.add(key);
    }
  }
  return allowlist;
}
